import { FK_ACTION_NAMES, type ColumnSnapshot, type FkAction } from '../../snapshot/types'

/**
 * Runtime + type representation of a column reference (e.g. `users.id`).
 * Carries the parent table name, the column's own name, plus runtime
 * accessors used by FK thunks and constraint builders.
 *
 * Exported so adopters can annotate self-referencing thunks without
 * spelling the shape inline:
 *
 *   parentId: uuid().references((): ColumnRef => categories.id)
 *
 * Without the annotation the initializer of a self-referencing const
 * trips TS7022 — TS needs to infer the const while the initializer
 * already references it.
 */
export interface ColumnRef {
  __tableName: string
  __name: string
  __builder: ColumnBuilder
  __state: () => ReturnType<ColumnBuilder['__state']>
}

/**
 * Resolved FK spec — `table` / `column` are pulled by invoking `thunk()`
 * lazily. The thunk pattern lets self-referencing tables work:
 *
 *   const categories = table('categories', {
 *     id: uuid().primaryKey().defaultRandom(),
 *     parentId: uuid().references((): ColumnRef => categories.id),
 *   })
 *
 * If we resolved at `.references()` call time, `categories` would TDZ-fail
 * inside its own initializer. Storing the thunk and resolving on read
 * (extract / render / emit) defers until after the const binding lands.
 */
/**
 * A column ref that knows its column's value type — what lets a foreign key
 * be checked against the column it points at (`fk()`). Assignable to
 * `ColumnRef`, so every existing ref-taking API keeps working.
 */
export type TypedColumnRef<T> = ColumnRef & { readonly __valueType?: T }

/** Typed refs for a column record — one per column. */
export type TypedColumnRefs<C> = {
  [K in keyof C]: TypedColumnRef<C[K] extends ColumnBuilder<infer T> ? T : never>
}

declare const SELF_REF: unique symbol
declare const SELF_REF_TO: unique symbol

/** What `selfRef('id')` returns: a target thunk that names a column of this table. */
export type SelfRef<K extends string> = (() => ColumnRef) & { readonly [SELF_REF]: K }

/**
 * A column whose foreign key is `fk(builder, selfRef(K))`, checked by `table()`
 * against its own columns. `.references()` can't carry it: a generic or
 * overloaded `.references()` makes a plain thunk in a class field circular (TS7022).
 */
export type SelfRefTo<K extends string> = { readonly [SELF_REF_TO]: K }

type SelfRefTarget<B> = B extends SelfRefTo<infer K> ? K : never
type ValueOf<B> = B extends ColumnBuilder<infer T> ? T : never

/**
 * `table()`'s check on its columns: each `selfRef(K)` names one of them, of a
 * type this column can hold. A failing column reads as the reason.
 */
export type CheckSelfRefs<C> = {
  [P in keyof C]: [SelfRefTarget<C[P]>] extends [never]
    ? C[P]
    : SelfRefTarget<C[P]> extends keyof C
      ? [ValueOf<C[SelfRefTarget<C[P]>]>] extends [ValueOf<C[P]>]
        ? C[P]
        : `selfRef('${SelfRefTarget<C[P]>}'): that column's type doesn't match this one`
      : `selfRef('${SelfRefTarget<C[P]>}'): this table has no such column`
}

export interface FkSpec {
  thunk: () => ColumnRef
  onDelete: FkAction
  onUpdate: FkAction
  /**
   * The constraint's name in the database.
   *
   * Omitted for schemas written by hand — the name is then derived as
   * `<table>_<column>_fk`. It is set when the schema was generated by
   * `kick db introspect`, because a database names its constraints itself:
   * Postgres' own default is `<table>_<column>_fkey`, and a DBA may have
   * chosen anything. Dropping the real name would make the next diff want to
   * rename every foreign key in the schema.
   */
  name?: string
}

/** Postgres array literal text: `{1,2}`, `{"a","b c"}`. */
function arrayLiteral(value: unknown[]): string {
  const item = (v: unknown): string =>
    v === null || v === undefined
      ? 'NULL'
      : Array.isArray(v)
        ? arrayLiteral(v)
        : typeof v === 'string' || v instanceof Date
          ? `"${(typeof v === 'string' ? v : dateLiteral(v)).replace(/["\\]/g, '\\$&')}"`
          : String(v)
  return `{${value.map(item).join(',')}}`
}

/** A Date's UTC time that Postgres, MySQL and SQLite all read: no `T`, no `Z`. */
function dateLiteral(d: Date): string {
  return d.toISOString().replace('T', ' ').replace('Z', '+00:00')
}

export interface ColumnState {
  type: string
  nullable: boolean
  default: string | null
  /** `default` is SQL to evaluate (`.defaultSql()`), not a value. */
  defaultSql?: boolean
  primaryKey: boolean
  unique: boolean
  references: FkSpec | null
  /**
   * A column kick/db maintains itself: `'updatedAt'` (set on every update),
   * `'version'` (incremented on every update), `'softDelete'` (rows with it
   * set are skipped by relational reads). Never part of the snapshot — it
   * changes queries, not the schema.
   */
  managed?: 'updatedAt' | 'version' | 'softDelete'
  generated?: { expression: string; stored: boolean }
  identity?: 'always' | 'byDefault'
  /**
   * How a bigint / numeric value is read back (`bigint({ mode })`,
   * `numeric(p, s, { mode })`). Unset, the driver's own value is returned.
   */
  mode?: 'bigint' | 'number' | 'string'
  /** `.comment()`: stored in the database on Postgres and MySQL. */
  comment?: string
  /** `.colName()`: the column's name in the database, when it isn't the key (or its `casing`). */
  colName?: string
  /** `tenantKey(tenancy)`: this is the table's tenant column. */
  tenancy?: { strategy: string; setting: string }
  /** `$defaultFn`: computed in JS for each inserted row that doesn't set it. */
  defaultFn?: () => unknown
  /** `$onUpdate`: computed in JS for each update that doesn't set it. */
  onUpdateFn?: () => unknown
}

/**
 * Type-only brand attached to a column when it's auto-assigned by the
 * database (serial / bigserial / smallserial), has a runtime default
 * (`.default(...)`), or carries an expression default
 * (`uuid().defaultRandom()`, `timestamp().defaultNow()`). `SchemaToTypes<S>`
 * reads this marker and wraps the column type in Kysely's `Generated<T>` so
 * adopters can omit the column on insert.
 *
 * Runtime is a no-op — the symbol never reaches a value.
 */
export const KICK_GENERATED = Symbol.for('@forinda/kickjs-db/Generated')
export type GeneratedBrand = { readonly [KICK_GENERATED]?: true }

/**
 * Type-only brand for a column the database always computes — a generated
 * column, or an identity `GENERATED ALWAYS`. `SchemaToTypes<S>` wraps it in
 * Kysely's `GeneratedAlways<T>`, so it can't be inserted or updated.
 */
export const KICK_GENERATED_ALWAYS = Symbol.for('@forinda/kickjs-db/GeneratedAlways')
export type GeneratedAlwaysBrand = { readonly [KICK_GENERATED_ALWAYS]?: true }

/**
 * Type-only brand attached to a column when `.notNull()` or `.primaryKey()`
 * is called. `SchemaToTypes<S>` reads this brand to decide whether the
 * column type is `T` (NOT NULL) or `T | null` (default nullable).
 *
 * Why a brand instead of a class generic: chained methods (notNull,
 * primaryKey) can return `this & NotNullBrand` to narrow nullability while
 * preserving the subclass identity — so `uuid().primaryKey().defaultRandom()`
 * still resolves `defaultRandom()` on `UuidBuilder`. A class generic
 * `<TNullable>` would collapse the subclass back to the parent.
 */
export const KICK_NOT_NULL = Symbol.for('@forinda/kickjs-db/NotNull')
export type NotNullBrand = { readonly [KICK_NOT_NULL]?: true }

/**
 * Re-attach the nullability / generated / selfRef brands after a transform that
 * must return a *new* builder type (e.g. `.array()` widening `T` to
 * `T[]`). Without this, `integer().notNull().array()` silently dropped
 * `NotNullBrand` and the row type regressed to `number[] | null`.
 *
 * Uses the same `extends` checks as `SchemaToTypes` (client/schema-types.ts)
 * so detection stays consistent in both directions.
 */
export type PreserveBrands<Self, Out> = Out &
  (Self extends NotNullBrand ? NotNullBrand : unknown) &
  (Self extends GeneratedBrand ? GeneratedBrand : unknown) &
  (Self extends GeneratedAlwaysBrand ? GeneratedAlwaysBrand : unknown) &
  (Self extends SelfRefTo<infer K> ? SelfRefTo<K> : unknown)

/**
 * Phantom-typed column builder. The `T` generic carries the column's TS
 * value type (number / string / Date / etc.); nullability is tracked via
 * the `NotNullBrand` intersection rather than a class generic so chain
 * methods preserve subclass identity.
 *
 * Both `T` and the brand are erased at runtime; they exist purely so
 * `SchemaToTypes<S>` can pull them out per column.
 */
export class ColumnBuilder<T = unknown> {
  // Phantom param shows up in the public surface so the type system sees
  // it. Reading it at runtime is intentionally not supported.
  declare readonly __t?: T

  protected state: ColumnState

  constructor(type: string, defaults: Partial<ColumnState> = {}) {
    this.state = {
      type,
      nullable: defaults.nullable ?? true,
      default: defaults.default ?? null,
      primaryKey: defaults.primaryKey ?? false,
      unique: defaults.unique ?? false,
      references: defaults.references ?? null,
      ...(defaults.mode ? { mode: defaults.mode } : {}),
    }
  }

  /**
   * `NOT NULL`: drops `| null` from the column's type.
   *
   * @example
   * name: text().notNull()
   */
  notNull(): this & NotNullBrand {
    this.state.nullable = false
    return this as this & NotNullBrand
  }

  /**
   * `PRIMARY KEY` (implies `NOT NULL`). For a key over several columns, use
   * `primaryKey().on(...)` in the table's constraints instead.
   *
   * @example
   * id: uuid().primaryKey().defaultRandom()
   */
  primaryKey(): this & NotNullBrand {
    this.state.primaryKey = true
    this.state.nullable = false
    return this as this & NotNullBrand
  }

  /**
   * `UNIQUE` on this column alone. Partial or multi-column: `unique(name).on(...)`
   * in the table's constraints.
   *
   * @example
   * email: varchar(320).notNull().unique()
   */
  unique(): this {
    this.state.unique = true
    return this
  }

  /**
   * An array of this type (`text[]`), typed `T[]`.
   *
   * @example
   * tags: text().array().notNull().default([])
   */
  array(): PreserveBrands<this, ColumnBuilder<T[]>> {
    this.state.type = `${this.state.type}[]`
    return this as unknown as PreserveBrands<this, ColumnBuilder<T[]>>
  }

  /**
   * A foreign key to another table's column. The target is a thunk, so tables
   * can be declared in any order. For a column of the same table, use
   * `selfRef('id')`; for two tables that point at each other, `link()`.
   * Actions: `'cascade'`, `'restrict'`, `'set_null'`, `'set_default'`,
   * `'no_action'` (the default). `name` overrides the derived constraint name.
   *
   * @example
   * authorId: uuid().notNull().references(() => users.id, { onDelete: 'cascade' })
   * parentId: uuid().references(selfRef('id'), { onDelete: 'set_null' })
   */
  references(
    target: () => ColumnRef,
    opts: { onDelete?: FkAction; onUpdate?: FkAction; name?: string } = {},
  ): this {
    // Checked here, where it's written: the schema is loaded without a type
    // check by `kick db generate`, and an unknown action reached the SQL as `undefined`.
    for (const key of ['onDelete', 'onUpdate'] as const) {
      const action = opts[key]
      if (action !== undefined && !(FK_ACTION_NAMES as readonly string[]).includes(action))
        throw new Error(
          `references(): ${key} '${action}' isn't an action — use ${FK_ACTION_NAMES.map(
            (a) => `'${a}'`,
          )
            .join(', ')
            .replace(/, ([^,]*)$/, ' or $1')}`,
        )
    }
    // Store the thunk — do NOT invoke it here. Self-referencing tables
    // pass `() => self.id` whose binding does not exist yet.
    this.state.references = {
      thunk: target,
      onDelete: opts.onDelete ?? 'no_action',
      onUpdate: opts.onUpdate ?? 'no_action',
      // Only carried when given: an absent name means "derive it", and
      // storing the derived value here would make it indistinguishable from
      // an explicit one that happens to match.
      ...(opts.name === undefined ? {} : { name: opts.name }),
    }
    return this
  }

  /**
   * Mark the column as having a runtime / DB-assigned default. The
   * `GeneratedBrand` flows into `SchemaToTypes<S>` so the column wraps
   * in `Generated<T>` — adopters can `INSERT` without specifying it.
   *
   * Accepts the natural literal for the column type — `boolean().default(false)`,
   * `integer().default(0)`, `varchar().default('active')`. Non-string
   * literals are normalised to their SQL-literal text so the snapshot
   * (`ColumnSnapshot.default: string | null`) and migration emitter stay
   * string-only. For a quoted string default the text is the value
   * itself (`'active'`); booleans/numbers emit bare (`false`, `0`). A JSON
   * column takes its value (`jsonb().default({})` stores `{}`), an array
   * column its array literal (`integer().array().default([1, 2])` stores
   * `{1,2}`), and a `Date` its UTC time (`2026-01-02 03:04:05.000+00:00`).
   */
  default(value: string | number | boolean | T): this & GeneratedBrand {
    this.state.default =
      typeof value === 'string'
        ? value
        : Array.isArray(value) && this.state.type.endsWith('[]')
          ? arrayLiteral(value)
          : value instanceof Date
            ? dateLiteral(value)
            : typeof value === 'object' && value !== null
              ? JSON.stringify(value)
              : String(value)
    this.state.defaultSql = false
    return this as this & GeneratedBrand
  }

  /**
   * A default that is SQL, evaluated by the database for each new row —
   * `id: text().primaryKey().defaultSql('gen_random_uuid()::text')`,
   * `slug: text().defaultSql("lower(hex(randomblob(8)))")`. `.default()` is a
   * value: on a text column `.default('now()')` stores the string `now()`.
   * Written as given, so it's your dialect's SQL.
   */
  defaultSql(expression: string): this & GeneratedBrand {
    this.state.default = expression
    this.state.defaultSql = true
    return this as this & GeneratedBrand
  }

  /**
   * A default computed in JS for each inserted row that doesn't set this
   * column — an id generator, a slug, a value from config:
   * `id: text().primaryKey().$defaultFn(() => ulid())`. Not part of the
   * schema: the database has no default, so raw SQL inserts must set it.
   */
  $defaultFn(fn: () => T): this & GeneratedBrand {
    this.state.defaultFn = fn
    return this as this & GeneratedBrand
  }

  /**
   * A value computed in JS for each update (and an upsert's update branch)
   * that doesn't set this column: `revisedBy: text().$onUpdate(() => currentUser())`.
   * Like `onUpdateNow()`, with your own value. Inserts don't call it.
   */
  $onUpdate(fn: () => T): this {
    this.state.onUpdateFn = fn
    return this
  }

  /**
   * Set this column to the current time on every update that doesn't set it
   * itself, and on an upsert's update branch. Your own value wins. Raw `sql`
   * updates don't maintain it.
   *
   * @example
   * updatedAt: timestamp().notNull().defaultNow().onUpdateNow()
   */
  onUpdateNow(): this {
    this.state.managed = 'updatedAt'
    return this
  }

  /**
   * Mark this column — a nullable timestamp — as the soft-delete marker:
   * relational reads (`db.query`) skip rows where it's set, at every level,
   * unless that level passes `withDeleted: true`. Soft-delete by setting it to
   * the current time; restore by setting it back to `null`.
   *
   * The query builder (`selectFrom`) is plain SQL and still sees deleted rows:
   * add `.where('deletedAt', 'is', null)` there yourself. No schema change.
   *
   * @example
   * deletedAt: timestamp().softDelete()
   * // delete:  db.updateTable('docs').set({ deletedAt: new Date() }).where('id', '=', id)
   * // include: db.query.docs.findMany({ withDeleted: true })
   */
  softDelete(): this {
    this.state.managed = 'softDelete'
    return this
  }

  /**
   * Computed by the database from other columns, on every write:
   * `total: numeric(12, 2).generatedAlwaysAs('price * quantity')`. The SQL is
   * passed through as written. Stored by default; `{ stored: false }` makes
   * it virtual, computed on read (MySQL, SQLite, Postgres 18+). It can't be
   * inserted or updated.
   */
  generatedAlwaysAs(
    expression: string,
    options: { stored?: boolean } = {},
  ): this & GeneratedAlwaysBrand {
    this.state.generated = { expression, stored: options.stored ?? true }
    return this as this & GeneratedAlwaysBrand
  }

  /**
   * An identity column the database numbers and won't let you set (Postgres)
   * — the SQL-standard successor to `serial`.
   */
  generatedAlwaysAsIdentity(): this & NotNullBrand & GeneratedAlwaysBrand {
    this.state.identity = 'always'
    this.state.nullable = false
    return this as this & NotNullBrand & GeneratedAlwaysBrand
  }

  /** An identity column the database numbers unless a value is given (Postgres). */
  generatedByDefaultAsIdentity(): this & NotNullBrand & GeneratedBrand {
    this.state.identity = 'byDefault'
    this.state.nullable = false
    return this as this & NotNullBrand & GeneratedBrand
  }

  /**
   * A comment stored with the column in the database, for whoever reads the
   * schema there (Postgres, MySQL; SQLite has none). Changing it migrates.
   */
  comment(text: string): this {
    this.state.comment = text
    return this
  }

  /**
   * The column's name in the database, when it isn't the key — a legacy
   * `EMAIL_ADDR` behind an `email` key. Taken as written: `casing` doesn't
   * change it. Queries, `db.query` and migrations use it; your code keeps the key.
   */
  colName(name: string): this {
    this.state.colName = name
    return this
  }

  /** The role kick/db maintains this column in, if any. */
  managedAs(): ColumnState['managed'] {
    return this.state.managed
  }

  toJSON(name: string): ColumnSnapshot {
    return {
      name,
      type: this.state.type,
      nullable: this.state.nullable,
      default: this.state.default,
      ...(this.state.defaultSql ? { defaultSql: true as const } : {}),
      primaryKey: this.state.primaryKey,
      // Only when set, so other columns serialize as they always have.
      ...(this.state.generated ? { generated: { ...this.state.generated } } : {}),
      ...(this.state.identity ? { identity: this.state.identity } : {}),
      ...(this.state.comment !== undefined ? { comment: this.state.comment } : {}),
    }
  }

  // Internal accessor for table()/diff to read full state including unique/references.
  __state(): Readonly<ColumnState> {
    return this.state
  }
}
