import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import type { Command } from 'commander'
import { TYPEGEN_OWNER_KEY } from '../typegen/dev-watcher'

/** One variable, as `app.describeConfig()` reports it. */
export interface ConfigVar {
  name: string
  required: boolean
  default?: unknown
  description?: string
  list: boolean
}

/** What `app.describeConfig()` returns. */
export interface ConfigDescription {
  env: ConfigVar[]
  sections: Array<{
    prefix: string
    declaredBy: string
    description?: string
    optional?: boolean
    vars: ConfigVar[]
  }>
}

/** Same symbols `@forinda/kickjs` reads — `Symbol.for`, so no import is needed. */
const ENTRY_CAPTURE = Symbol.for('kickjs.handler.entryCapture')
const DESCRIBE_CONFIG = Symbol.for('kickjs.config.describe')

const HEADER = `# Generated by \`kick env example\` from the env schema and the declared settings
# sections. Re-run it after changing them; \`kick env example --check\` fails when stale.
#
# Uncommented variables are required. Commented ones are optional; the value shown
# is the default. Any variable can come from a file instead: NAME_FILE=/run/secrets/name`

function formatDefault(value: unknown): string {
  if (Array.isArray(value)) return value.join(',')
  if (value !== null && typeof value === 'object') return JSON.stringify(value)
  // A newline would end the commented line; dotenv reads "\n" in double quotes.
  if (typeof value === 'string' && /[\r\n]/.test(value)) return JSON.stringify(value)
  return String(value)
}

/** Each line of `text` as a comment — a newline would end a commented line. */
const commentLines = (text: string) => text.split(/\r?\n/).map((line) => `# ${line}`)

function renderVars(vars: ConfigVar[], optional = false): string[] {
  const lines: string[] = []
  for (const v of vars) {
    const notes = [
      v.description,
      v.list ? 'comma-separated list' : undefined,
      // An optional section's required variables stay commented: needed once it's used.
      optional && v.required ? 'required when used' : undefined,
    ].filter(Boolean)
    if (notes.length > 0) lines.push(...commentLines(notes.join(' — ')))
    if (v.required && !optional) lines.push(`${v.name}=`)
    else lines.push(`# ${v.name}=${v.default === undefined ? '' : formatDefault(v.default)}`)
  }
  return lines
}

/** The `.env.example` text for a described config. Pure — no I/O. */
export function renderEnvExample(config: ConfigDescription): string {
  const blocks: string[] = [HEADER]
  if (config.env.length > 0) {
    blocks.push(['# ── App env schema ──', ...renderVars(config.env)].join('\n'))
  }
  for (const section of config.sections) {
    blocks.push(
      [
        `# ── ${section.prefix} settings (${section.optional ? 'optional, ' : ''}declared by ${section.declaredBy}) ──`,
        ...(section.description ? commentLines(section.description) : []),
        ...renderVars(section.vars, section.optional),
      ].join('\n'),
    )
  }
  return `${blocks.join('\n\n')}\n`
}

/**
 * Load the app's entry through the project's Vite config — the same pipeline
 * `kick dev` uses (SWC decorators, path aliases) — with `bootstrap()` captured
 * instead of started and the env loaders in describe mode, then ask the app
 * to describe its config. Nothing listens; no environment is validated.
 */
async function describeProject(cwd: string, entry: string): Promise<ConfigDescription> {
  const entryPath = resolve(cwd, entry)
  if (!existsSync(entryPath)) throw new Error(`${entry} not found`)
  const configFile = resolve(cwd, 'vite.config.ts')
  if (!existsSync(configFile)) {
    throw new Error('vite.config.ts not found — kick env example loads the app through it')
  }

  const { createRequire } = await import('node:module')
  const require = createRequire(resolve(cwd, 'package.json'))
  const { createServer } = await import(pathToFileURL(require.resolve('vite')).href)

  const g = globalThis as Record<string | symbol, unknown>
  let captured: { describeConfig(): ConfigDescription } | undefined
  g[ENTRY_CAPTURE] = (app: unknown) => {
    captured ??= app as typeof captured
  }
  g[DESCRIBE_CONFIG] = true
  // Keep the kickjs Vite plugin's typegen from running for a one-off load.
  g[TYPEGEN_OWNER_KEY] = 'kick-env'

  const server = await createServer({
    configFile,
    root: cwd,
    logLevel: 'error',
    appType: 'custom',
    server: { middlewareMode: true, hmr: false, watch: null },
  })
  try {
    await server.ssrLoadModule(entryPath)
  } finally {
    delete g[ENTRY_CAPTURE]
    delete g[DESCRIBE_CONFIG]
    delete g[TYPEGEN_OWNER_KEY]
    await server.close()
  }
  if (!captured) {
    throw new Error(`${entry} finished loading without calling bootstrap()`)
  }
  return captured.describeConfig()
}

export function registerEnvCommand(program: Command): void {
  const env = program.command('env').description('Work with the environment the app reads')

  env
    .command('example')
    .description('Write .env.example from the env schema and declared settings sections')
    .option('-e, --entry <file>', 'App entry that calls bootstrap()', 'src/index.ts')
    .option('-o, --out <file>', 'File to write', '.env.example')
    .option('--check', 'Exit 1 if the file is missing or out of date, instead of writing it')
    .action(async (opts: { entry: string; out: string; check?: boolean }) => {
      const cwd = process.cwd()
      const outPath = resolve(cwd, opts.out)
      let text: string
      try {
        text = renderEnvExample(await describeProject(cwd, opts.entry))
      } catch (err) {
        console.error(`\n  kick env example: ${(err as Error).message}\n`)
        process.exit(1)
      }
      if (opts.check) {
        const current = existsSync(outPath) ? readFileSync(outPath, 'utf8') : undefined
        if (current !== text) {
          console.error(`\n  ${opts.out} is out of date — run \`kick env example\`.\n`)
          process.exit(1)
        }
        console.log(`  ${opts.out} is up to date.`)
        return
      }
      writeFileSync(outPath, text)
      console.log(`  Wrote ${opts.out}`)
    })
}
